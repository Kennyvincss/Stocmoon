// Exports ABIs from Foundry build output into packages/core/src/abi/*.ts (as const for viem type inference).
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "../../..");
const out = join(root, "packages/core/src/abi");
mkdirSync(out, { recursive: true });
const contracts = ["StocMoonMarkets", "StocMoonLens", "OracleAdapter", "MirrorAggregator"];
const index = [];
for (const name of contracts) {
  const artifact = JSON.parse(readFileSync(join(root, `contracts/out/${name}.sol/${name}.json`), "utf8"));
  const varName = name[0].toLowerCase() + name.slice(1) + "Abi";
  writeFileSync(
    join(out, `${name}.ts`),
    `// Generated by packages/core/scripts/export-abi.mjs from contracts/out. Do not edit.\nexport const ${varName} = ${JSON.stringify(artifact.abi, null, 2)} as const;\n`,
  );
  index.push(`export { ${varName} } from "./${name}";`);
}
writeFileSync(join(out, "index.ts"), index.join("\n") + "\nexport { erc20Abi } from \"viem\";\nexport { aggregatorV3Abi } from \"./aggregator\";\n");
console.log("ABIs exported:", contracts.join(", "));
