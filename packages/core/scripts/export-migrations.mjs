// Embeds db/migrations/*.sql into packages/core/src/migrations.ts so serverless apps (Vercel) can create the schema.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "../../..");
const dir = join(root, "db/migrations");
const items = readdirSync(dir).filter((f) => f.endsWith(".sql")).sort()
  .map((f) => `  { version: ${JSON.stringify(f)}, sql: ${JSON.stringify(readFileSync(join(dir, f), "utf8"))} },`);
writeFileSync(join(root, "packages/core/src/migrations.ts"),
  `// Generated by packages/core/scripts/export-migrations.mjs from db/migrations. Do not edit.\nexport const MIGRATIONS: { version: string; sql: string }[] = [\n${items.join("\n")}\n];\n`);
console.log("migrations embedded:", items.length);
